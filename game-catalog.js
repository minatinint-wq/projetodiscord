function slug(value) {
  return value
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/[^a-z0-9]+/g, "-")
    .replace(/^-|-$/g, "");
}
function hue(value) {
  let hash = 0;
  for (const character of value) hash = (hash * 31 + character.charCodeAt(0)) >>> 0;
  return hash % 360;
}
export const GAME_CATALOG = GAME_TITLES.slice(0, 400).map((name, index) => ({
  id: `${slug(name)}-${index + 1}`,
  name,
  icon: `game-${hue(name)}`,
  accent: `hsl(${hue(name)} 72% 55%)`,
}));
export const GAME_IDS = new Set(GAME_CATALOG.map((game) => game.id));
